import { expect, test, toggle } from '../../fixtures'

test('query source paginates, accumulates infinite pages and changes collection', async ({ page, grid }) => {
	await grid.open('query-source')
	await expect(grid.rows()).toHaveCount(3)
	await expect(page.getByText('Ada', { exact: true })).toBeVisible()
	await page.getByRole('button', { name: 'Next', exact: true }).click()
	await expect(page.getByText('Dorothy', { exact: true })).toBeVisible()
	await expect(page.getByText('Ada', { exact: true })).toHaveCount(0)
	await page.getByLabel('Pagination mode').selectOption('infinite')
	await expect(page.getByText('Ada', { exact: true })).toBeVisible()
	await expect(grid.rows()).toHaveCount(3)
	await page.getByRole('button', { name: /load more/i }).click()
	await expect(grid.rows()).toHaveCount(6)
	await page.getByRole('searchbox', { name: /search/i }).fill('Grace')
	await expect(page.getByText('Grace', { exact: true })).toBeVisible()
	await expect(grid.rows()).toHaveCount(1)
	await page.getByLabel('Pagination mode').selectOption('pages')
	await expect(grid.rows()).toHaveCount(1)
	await expect(page.getByText('Grace', { exact: true })).toBeVisible()
})

test('query demo creates, edits and deletes fake users through the connector', async ({ page, grid }) => {
	await grid.open('query-source')
	await expect(grid.rows()).toHaveCount(3)
	await page.getByRole('button', { name: '+ Add', exact: true }).click()
	const dialog = page.getByRole('dialog')
	await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill('New user')
	await dialog.getByRole('button', { name: 'Save', exact: true }).click()
	await expect(dialog).toHaveCount(0)
	await expect(page.getByText('New user', { exact: true })).toBeVisible()
	const created = grid.rows().filter({ hasText: 'New user' })
	await created.getByRole('button', { name: 'Edit', exact: true }).click()
	await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill('Updated user')
	await dialog.getByRole('button', { name: 'Save', exact: true }).click()
	await expect(dialog).toHaveCount(0)
	await expect(page.getByText('Updated user', { exact: true })).toBeVisible()
	await grid.rows().filter({ hasText: 'Updated user' }).getByRole('button', { name: 'Delete', exact: true }).click()
	await expect(page.getByText('Updated user', { exact: true })).toHaveCount(0)
	await expect(page.getByText('Ada', { exact: true })).toBeVisible()
	const checkboxes = page.locator('[data-slot="tbody"]').getByRole('checkbox')
	await toggle(checkboxes.first())
	await toggle(checkboxes.nth(1))
	await page.locator('[data-slot="action-bar"]').getByRole('button', { name: 'Delete', exact: true }).click()
	await expect(page.getByText('Ada', { exact: true })).toHaveCount(0)
	await expect(page.getByText('Barbara', { exact: true })).toHaveCount(0)
	await expect(page.getByText('Carol', { exact: true })).toBeVisible()
})
