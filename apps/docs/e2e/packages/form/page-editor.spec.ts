import { expect, test } from '../../fixtures'

test('page and modal drafts save and discard independently', async ({ form, page }) => {
	await form.open('form-page-editor')
	const save = page.getByRole('button', { name: 'Save changes' })
	const title = form.input('title')
	await expect(save).toBeDisabled()
	await title.fill('Updated workflow')
	await expect(save).toBeEnabled()
	await title.fill('Customer onboarding')
	await expect(save).toBeDisabled()

	await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
	await page.getByRole('textbox', { name: 'Step title' }).fill('Cancelled title')
	await page.getByRole('button', { name: 'Cancel' }).click()
	await expect(page.getByText('Send a welcome email')).toBeVisible()
	await expect(save).toBeDisabled()

	await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
	await page.getByRole('textbox', { name: 'Step title' }).fill('Edited step')
	await page.getByRole('button', { name: 'Apply changes' }).click()
	await expect(page.getByText('Edited step')).toBeVisible()
	await expect(save).toBeEnabled()
	await page.getByRole('button', { name: 'Discard changes' }).click()
	await expect(page.getByText('Send a welcome email')).toBeVisible()

	await page.getByRole('button', { name: 'Add step', exact: true }).click()
	await page.getByRole('textbox', { name: 'Step title' }).fill('A new step')
	await page.getByRole('button', { name: 'Add step', exact: true }).last().click()
	await expect(page.getByText('A new step')).toBeVisible()
	await save.click()
	await expect(save).toBeDisabled()
	await title.fill('Another draft')
	await page.getByRole('button', { name: 'Discard changes' }).click()
	await expect(title).toHaveValue('Customer onboarding')
	await expect(page.getByText('A new step')).toBeVisible()

	await page.getByLabel('Condition 1 value').fill('France')
	await expect(save).toBeEnabled()
	await page.getByRole('button', { name: 'Discard changes' }).click()
	await expect(page.getByLabel('Condition 1 value')).toHaveValue('Germany')
})

test('reorders and removes steps, then discards the changes', async ({ form, page }) => {
	await form.open('form-page-editor')
	const rows = page.locator('details > summary')
	await expect(rows).toHaveText(['Send a welcome email', 'Schedule a kickoff'])
	const handle = page.getByRole('button', { name: 'Reorder Send a welcome email' })
	await handle.focus()
	await page.keyboard.press('Space')
	await page.keyboard.press('ArrowDown')
	await page.keyboard.press('Space')
	await expect(rows).toHaveText(['Schedule a kickoff', 'Send a welcome email'])
	await page.getByRole('button', { name: 'Remove Schedule a kickoff' }).click()
	await expect(rows).toHaveText(['Send a welcome email'])
	await page.getByRole('button', { name: 'Discard changes' }).click()
	await expect(rows).toHaveText(['Send a welcome email', 'Schedule a kickoff'])
})
