import { expect, test } from '@playwright/test'

test('mutation preserves invalid input, refreshes the list on success and resets the form', async ({ page }) => {
	await page.goto('/docs/query-react/mutation-workflows')
	const demo = page.getByRole('region', { name: 'Create devices' })
	await expect(demo.getByRole('listitem').first()).toHaveText('Weather station')
	const name = demo.getByRole('textbox', { name: 'Device name' })
	await name.fill('ab')
	await demo.getByRole('button', { name: 'Add device' }).click()
	await expect(demo.getByRole('alert')).toHaveText('Use at least 3 characters.')
	await expect(name).toHaveValue('ab')
	await expect(name).toHaveAttribute('aria-invalid', 'true')
	await name.fill('Office sensor')
	await demo.getByRole('button', { name: 'Add device' }).click()
	await expect(demo.getByRole('button', { name: 'Saving…' })).toBeDisabled()
	await expect(demo.getByRole('listitem').filter({ hasText: 'Office sensor' })).toBeVisible()
	await expect(demo.getByRole('button', { name: 'Add device' })).toBeEnabled()
	await expect(name).toHaveValue('')
	await expect(demo.getByRole('alert')).toHaveCount(0)
})

test('optimistic changes appear immediately, roll back on failure and persist on success', async ({ page }) => {
	await page.goto('/docs/query-react/mutation-workflows')
	const demo = page.getByRole('region', { name: 'Optimistic favorites' })
	const favorite = demo.getByRole('button', { name: 'Favorite Weather station', exact: true })
	await expect(favorite).toHaveAttribute('aria-pressed', 'false')
	await demo.getByRole('checkbox', { name: 'Reject changes on the server' }).check()
	await favorite.click()
	await expect(favorite).toHaveAttribute('aria-pressed', 'true')
	await expect(favorite).toBeDisabled()
	await expect(demo.getByRole('alert')).toContainText('previous list has been restored')
	await expect(favorite).toHaveAttribute('aria-pressed', 'false')
	await expect(favorite).toBeEnabled()
	await demo.getByRole('checkbox', { name: 'Reject changes on the server' }).uncheck()
	await favorite.click()
	await expect(favorite).toBeEnabled()
	await expect(favorite).toHaveAttribute('aria-pressed', 'true')
	await expect(demo.getByRole('alert')).toHaveCount(0)
})

test('infinite query keeps previous pages after an error and continues pagination on retry', async ({ page }) => {
	await page.goto('/docs/query-react/infinite-query')
	const demo = page.getByRole('region', { name: 'Paginated devices' })
	await expect(demo.getByRole('listitem')).toHaveCount(3)
	await demo.getByRole('button', { name: 'Fail next page' }).click()
	await expect(demo.getByRole('button', { name: 'Loading more…' })).toBeDisabled()
	await expect(demo.getByRole('listitem')).toHaveCount(3)
	await expect(demo.getByRole('alert')).toContainText('Page request failed')
	await expect(demo.getByRole('listitem')).toHaveCount(3)
	await demo.getByRole('button', { name: 'Load more', exact: true }).click()
	await expect(demo.getByRole('listitem')).toHaveCount(6)
	await expect(demo.getByRole('alert')).toHaveCount(0)
	await demo.getByRole('button', { name: 'Load more', exact: true }).click()
	await expect(demo.getByRole('listitem')).toHaveCount(9)
	await expect(demo.getByRole('button', { name: 'All devices loaded' })).toBeDisabled()
})

