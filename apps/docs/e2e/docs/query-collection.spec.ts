import { expect, test } from '@playwright/test'

test('ordinary collection supports paging, atomic search reset and CRUD actions', async ({ page }) => {
	await page.goto('/docs/query-react/collection')
	const example = page.getByRole('region', { name: 'Collection users' })
	await expect(example.getByLabel('Name for Ada', { exact: true })).toBeVisible()
	await example.getByRole('button', { name: 'Next', exact: true }).click()
	await expect(example.getByText('Page 2', { exact: true })).toBeVisible()
	await example.getByLabel('Search users', { exact: true }).fill('Ada')
	await expect(example.getByText('Page 1', { exact: true })).toBeVisible()
	await expect(example.getByLabel('Name for Ada', { exact: true })).toBeVisible()
	await example.getByLabel('Search users', { exact: true }).fill('')
	await example.getByLabel('New user name', { exact: true }).fill('New user')
	await example.getByRole('button', { name: 'Create', exact: true }).click()
	await expect(example.getByRole('status')).toHaveText('6 users')
	const ada = example.getByRole('listitem').filter({ has: page.getByLabel('Name for Ada', { exact: true }) })
	await ada.getByLabel('Name for Ada', { exact: true }).fill('Ada updated')
	await ada.getByRole('button', { name: 'Save', exact: true }).click()
	await expect(example.getByLabel('Name for Ada updated', { exact: true })).toBeVisible()
	await example.getByLabel('Select Ada updated', { exact: true }).check()
	await example.getByLabel('Select Grace', { exact: true }).check()
	await example.getByRole('button', { name: 'Delete selected', exact: true }).click()
	await expect(example.getByRole('status')).toHaveText('4 users')
	await example.getByRole('button', { name: 'Next', exact: true }).click()
	await expect(example.getByText('Page 2', { exact: true })).toBeVisible()
	await example.getByRole('button', { name: 'Delete', exact: true }).last().click()
	await expect(example.getByRole('status')).toHaveText('3 users')
	await example.getByRole('button', { name: 'Delete', exact: true }).last().click()
	await expect(example.getByText('Page 1', { exact: true })).toBeVisible()
	await expect(example.getByRole('status')).toHaveText('2 users')
})
